/// Objects' own halves of clips whose actor isn't named for the object (the pool table's
/// `_pool`, the drum kit's `_drumKit`, the waste chute's `_trashchute`).
pub const OBJECT_ACTORS: &[&str] = &["pool", "arcadeClaw", "bull", "drumKit", "trashChute", "washer", "machine"];

/// Whether a clip should be baked.
pub fn wanted(name: &str) -> bool {
    // (The Sim's side, a prop's, or the object's own: `a2o_fridge_openDoor_fridge` swings its
    // door as the Sim opens it.)
    let actor_side = |n: &str| {
        n.ends_with("_x")
            || n.ends_with("_y")
            || n.rsplit_once('_').is_some_and(|(_, a)| {
                PROP_ACTORS.iter().chain(OBJECT_ACTORS).any(|p| p.eq_ignore_ascii_case(a)) || n.split('_').nth(1).is_some_and(|o| o.eq_ignore_ascii_case(a))
            })
    };
    CLIP_PREFIXES.iter().any(|p| {
        if !name.starts_with(p) {
            return false;
        }
        let object_or_social = ["a2o_", "a2a_", "a2c_", "c2a_", "c2c_", "c2o_", "p2o_", "b2o_", "a2b_", "a2p_"].iter().any(|p| name.starts_with(p));
        !object_or_social || actor_side(name)
    })
}

/// Pack key of a clip by name.
pub fn clip_key(name: &str) -> crate::types::Key {
    (s3pkg::types::CLIP, 0, s3pkg::fnv64(&name.to_ascii_lowercase()))
}

